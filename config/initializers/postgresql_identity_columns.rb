# frozen_string_literal: true

# Create primary keys as identity columns instead of `bigserial`.
#
# `bigserial` is PostgreSQL's own pre-standard shorthand: an ordinary bigint
# with a `DEFAULT nextval(...)` pointing at a separately-created sequence.
# Identity columns are the SQL-standard replacement, available since
# PostgreSQL 10. The sequence is owned by the column rather than merely
# referenced by it, so it cannot be dropped, renamed or attached elsewhere
# behind the table's back, and the column carries no rewritable DEFAULT that
# an accidental `ALTER COLUMN ... SET DEFAULT` could quietly replace.
#
# BY DEFAULT, not ALWAYS: explicit ids have to keep working. Fixtures assign
# their own, and so does `pg_restore` of a dump — see script/fetch-prod-db.
#
# It also matches Ecto, which built the tables carried over from the Elixir
# app as identity columns. See db/transition/README.md.
ActiveSupport.on_load(:active_record_postgresqladapter) do
  ActiveRecord::ConnectionAdapters::PostgreSQLAdapter::NATIVE_DATABASE_TYPES[:primary_key] =
    "bigint primary key generated by default as identity"
end
